function AuthPanel({
  authMode,
  copy,
  onAuthModeChange,
  onSignedIn
}: {
  authMode: "login" | "register";
  copy: typeof COPY[UiLanguage];
  onAuthModeChange: (mode: "login" | "register") => void;
  onSignedIn: (user: UserSession) => void;
}) {
  const [displayName, setDisplayName] = useState("");
  const [email, setEmail] = useState("");
  const [password, setPassword] = useState("");
  const [authError, setAuthError] = useState<string | null>(null);
  const [isSubmitting, setIsSubmitting] = useState(false);

  const submit = async () => {
    setIsSubmitting(true);
    setAuthError(null);

    try {
      const response = await fetch(`/api/auth/${authMode}`, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ displayName, email, password })
      });
      const payload = await response.json();
      if (!response.ok) {
        throw new Error(payload.message ?? "Authentication failed");
      }
      onSignedIn(payload.user);
    } catch (error) {
      setAuthError(error instanceof Error ? error.message : "Authentication failed");
    } finally {
      setIsSubmitting(false);
    }
  };

  return (
    <section className="mx-auto max-w-md rounded-lg border bg-card p-5 shadow-sm">
      <div className="mb-4 flex items-center gap-2">
        <UserPlus className="h-5 w-5 text-primary" />
        <h1 className="text-xl font-semibold">{authMode === "login" ? copy.login : "Register"}</h1>
      </div>
      <div className="space-y-3">
        {authMode === "register" ? (
          <input
            className="h-10 w-full rounded-md border bg-background px-3 text-sm outline-none focus:ring-2 focus:ring-ring"
            value={displayName}
            onChange={(event) => setDisplayName(event.target.value)}
            placeholder="Display name"
          />
        ) : null}
        <input
          className="h-10 w-full rounded-md border bg-background px-3 text-sm outline-none focus:ring-2 focus:ring-ring"
          value={email}
          onChange={(event) => setEmail(event.target.value)}
          placeholder="Email"
          type="email"
        />
        <input
          className="h-10 w-full rounded-md border bg-background px-3 text-sm outline-none focus:ring-2 focus:ring-ring"
          value={password}
          onChange={(event) => setPassword(event.target.value)}
          placeholder="Password"
          type="password"
        />
        {authError ? <StatusTone tone="error" text={authError} /> : null}
        <Button className="w-full" onClick={submit} disabled={isSubmitting}>
          <LogIn className="h-4 w-4" />
          {isSubmitting ? "Submitting" : authMode === "login" ? copy.login : "Create account"}
        </Button>
        <Button
          className="w-full"
          variant="ghost"
          onClick={() => onAuthModeChange(authMode === "login" ? "register" : "login")}
        >
          {authMode === "login" ? "Need an account?" : "Already have an account?"}
        </Button>
      </div>
    </section>
  );
}

