function shiftLineTiming(line: LyricLine, delta: number): LyricLine {
  const startTime = Math.max(0, line.startTime + delta);
  const endTime = Math.max(startTime + 0.2, line.endTime + delta);

  return {
    ...line,
    startTime,
    endTime,
    words: line.words.map((word) => ({
      ...word,
      startTime: Math.max(0, word.startTime + delta),
      endTime: Math.max(0.2, word.endTime + delta)
    }))
  };
}

function moveLineToStart(line: LyricLine, nextStartTime: number): LyricLine {
  const delta = Math.max(0, nextStartTime) - line.startTime;
  return shiftLineTiming(line, delta);
}

function setLineDuration(line: LyricLine, duration: number): LyricLine {
  const nextDuration = Math.max(0.2, duration);
  const previousDuration = Math.max(0.2, line.endTime - line.startTime);

  return {
    ...line,
    endTime: line.startTime + nextDuration,
    words: line.words.map((word) => {
      const startRatio = (word.startTime - line.startTime) / previousDuration;
      const endRatio = (word.endTime - line.startTime) / previousDuration;
      return {
        ...word,
        startTime: line.startTime + nextDuration * startRatio,
        endTime: line.startTime + nextDuration * endRatio
      };
    })
  };
}

function makeInsertedLine(id: string, startTime: number): LyricLine {
  const safeStart = Math.max(0, startTime);
  const text = "New lyric";
  return {
    id,
    startTime: safeStart,
    endTime: safeStart + 2,
    text,
    words: [
      {
        id: `${id}-word-1`,
        text,
        startTime: safeStart,
        endTime: safeStart + 2
      }
    ]
  };
}

function shiftWordTiming(line: LyricLine, wordId: string, delta: number): LyricLine {
  return {
    ...line,
    words: line.words.map((word) => {
      if (word.id !== wordId) {
        return word;
      }

      const duration = Math.max(0.05, word.endTime - word.startTime);
      const startTime = clamp(word.startTime + delta, line.startTime, line.endTime - 0.05);
      return {
        ...word,
        startTime,
        endTime: Math.min(line.endTime, startTime + duration)
      };
    })
  };
}

function resizeWordDuration(line: LyricLine, wordId: string, delta: number): LyricLine {
  return {
    ...line,
    words: line.words.map((word) => {
      if (word.id !== wordId) {
        return word;
      }

      const duration = Math.max(0.05, word.endTime - word.startTime + delta);
      return {
        ...word,
        endTime: Math.min(line.endTime, word.startTime + duration)
      };
    })
  };
}

function clamp(value: number, min: number, max: number) {
  return Math.min(max, Math.max(min, value));
}

function toLrcText(lines: LyricLine[]) {
  return lines.map((line) => `[${formatLrcTime(line.startTime)}]${line.text}`).join("\n");
}

function formatLrcTime(totalSeconds: number) {
  const minutes = Math.floor(totalSeconds / 60);
  const seconds = Math.floor(totalSeconds % 60);
  const hundredths = Math.floor((totalSeconds % 1) * 100);

  return `${String(minutes).padStart(2, "0")}:${String(seconds).padStart(2, "0")}.${String(hundredths).padStart(2, "0")}`;
}
